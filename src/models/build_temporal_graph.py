"""
Converts the fresh address sample's transfer edges into a PyTorch Geometric TemporalData object
for TGN training, with per-event supervision from the soft labels generated by src/models/generate_soft_labels.py

Scope decisions:
- msg (edge features): log(value), log(gasUsed), log(gasPrice) - the minimal set for MVP v1
- Supervision target: only the sender of each transfer is supervised, against its own
  day-level consensus_score from eth_fresh_soft_labels.parquet - the receiver is passive
- Mint/burn (null-address) edges are excluded from the graph entirely - including protocol sentinel
  addresses as real graph nodes would create false proximity between unrelated addresses.
- Contracts remain in the graph as structural nodes (they can be src/dst of real edges) but are
  never supervised - those events still update memory during training, their loss contribution
  is just masked out
- Split: days 1-11 train, 12-14 validation
"""

from pathlib import Path

import numpy as np
import pandas as pd
import torch
from torch_geometric.data import TemporalData

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SAMPLE_PATH = PROJECT_ROOT / "data" / "interim" / "eth_fresh_sample.parquet"
SOFT_LABELS_PATH = PROJECT_ROOT / "data" / "processed" / "eth_fresh_soft_labels.parquet"
OUTPUT_PATH = PROJECT_ROOT / "data" / "processed" / "eth_fresh_temporal_graph.pt"

NULL_ADDRESSES = {
    "0x0000000000000000000000000000000000000000",
    "0x000000000000000000000000000000000000dead",
}

TRAIN_DAYS = set(range(1, 12))  # days 1-11
VAL_DAYS = set(range(12, 15))  # days 12-14


def load_edges() -> pd.DataFrame:
    df = pd.read_parquet(SAMPLE_PATH)
    df = df[~df["from"].isin(NULL_ADDRESSES) & ~df["to"].isin(NULL_ADDRESSES)]
    return df.sort_values("timeStamp").reset_index(drop=True)


def build_node_index(df: pd.DataFrame) -> dict:
    addresses = pd.unique(pd.concat([df["from"], df["to"]]))
    return {addr: i for i, addr in enumerate(addresses)}


def assign_day(timestamps: np.ndarray, window_start: pd.Timestamp) -> np.ndarray:
    seconds_since_start = timestamps - int(window_start.timestamp())
    return (seconds_since_start // 86400 + 1).astype(int)  # matches build_time_snapshots.py


def build_labels_lookup(soft_labels_path: Path) -> dict:
    labels = pd.read_parquet(soft_labels_path, columns=["consensus_score", "snapshot_day"])
    labels.index.name = "address"
    labels = labels.reset_index()
    return {
        (row.address, int(row.snapshot_day)): float(row.consensus_score)
        for row in labels.itertuples()
    }


def main() -> None:
    df = load_edges()
    node_index = build_node_index(df)
    window_start = pd.Timestamp(df["timeStamp"].min(), unit="s", tz="UTC").floor("D")
    day = assign_day(df["timeStamp"].to_numpy(), window_start)

    label_lookup = build_labels_lookup(SOFT_LABELS_PATH)
    y = np.array(
        [label_lookup.get((addr, d), np.nan) for addr, d in zip(df["from"], day)],
        dtype=np.float32,
    )
    mask = ~np.isnan(y)
    print(
        f"{mask.sum():,} / {len(df):,} events have a supervision label "
        f"({(~mask).sum():,} unlabeled - src is a contract or otherwise missing)"
    )

    src = torch.tensor(df["from"].map(node_index).to_numpy(), dtype=torch.long)
    dst = torch.tensor(df["to"].map(node_index).to_numpy(), dtype=torch.long)
    t = torch.tensor(df["timeStamp"].to_numpy(), dtype=torch.long)
    msg = torch.tensor(
        np.stack(
            [
                np.log1p(df["value"].to_numpy()),
                np.log1p(df["gasUsed"].to_numpy(dtype=np.float64)),
                np.log1p(df["gasPrice"].to_numpy(dtype=np.float64)),
            ],
            axis=1,
        ),
        dtype=torch.float,
    )

    data = TemporalData(src=src, dst=dst, t=t, msg=msg)
    data.y = torch.tensor(np.nan_to_num(y, nan=0.0), dtype=torch.float)
    data.y_mask = torch.tensor(mask, dtype=torch.bool)
    data.day = torch.tensor(day, dtype=torch.long)
    data.train_mask = torch.tensor(np.isin(day, list(TRAIN_DAYS)), dtype=torch.bool)
    data.val_mask = torch.tensor(np.isin(day, list(VAL_DAYS)), dtype=torch.bool)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    torch.save({"data": data, "node_index": node_index}, OUTPUT_PATH)

    print(f"nodes: {len(node_index):,}  events: {src.size(0):,}")
    print(f"train events: {int(data.train_mask.sum()):,}  val events: {int(data.val_mask.sum()):,}")
    print(f"saved to: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()